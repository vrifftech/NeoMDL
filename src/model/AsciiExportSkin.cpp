void writeSkin(Writer& writer,const Model&,const Mesh& mesh,
               const ReconstructedMesh& generated) {
    const auto& skin=*mesh.asciiSkinSource;
    writer.line("skinbonemap "+std::to_string(skin.boneToPalette.size()));
    for(const auto value:skin.boneToPalette) writer.line(writer.scalar(value));
    writer.line("skinpalette "+std::to_string(skin.paletteToBone.size()));
    for(const auto value:skin.paletteToBone) writer.line(std::to_string(value));
    writer.line("skinbindrotations "+std::to_string(skin.inverseOrientations.size()));
    for(const auto& q:skin.inverseOrientations)
        writer.line(writer.vector({q.x,q.y,q.z})+" "+writer.scalar(q.w));
    writer.line("skinbindtranslations "+std::to_string(skin.inverseTranslations.size()));
    for(const auto value:skin.inverseTranslations) writer.line(writer.vector(value));
    writer.line("boneconstantindices "+std::to_string(mesh.boneConstantIndices.size()));
    for(const auto value:mesh.boneConstantIndices) writer.line(std::to_string(value));
    const auto channels=decodeEngineFloatSkinChannels(mesh);
    writer.line("skinweights "+std::to_string(generated.sourceVertices.size()));
    for(const auto source:generated.sourceVertices) {
        const auto& value=channels.at(source);
        std::string row;
        for(const auto weight:value.weights) row+=writer.scalar(weight)+" ";
        for(std::size_t i=0;i<4u;++i) row+=writer.scalar(value.indices[i])+(i==3u?"":" ");
        writer.line(row);
    }
}

void writeLightsaber(Writer& writer,const Node& node,bool explicitNormals) {
    const auto& saber=*node.lightsaber;
    constexpr auto back=LightsaberNodeData::backPieceOffset;
    // Triangulate the two eight-vertex blade strips. Segment rows are copies
    // of their first four piece rows, regenerated by InternalPostProcess.
    constexpr std::array<std::size_t,16> pieces{{
        0,1,2,3,4,5,6,7,back,back+1,back+2,back+3,back+4,back+5,back+6,back+7}};
    constexpr std::array<std::array<std::size_t,3>,12> faces{{
        {{0,4,5}},{{0,5,1}},{{1,5,6}},{{1,6,2}},{{2,6,7}},{{2,7,3}},
        {{13,12,8}},{{9,13,8}},{{14,13,9}},{{10,14,9}},{{15,14,10}},{{11,15,10}}}};
    std::array<Vec3,faces.size()> normals{};
    for(std::size_t i=0;i<faces.size();++i) {
        const auto a=saber.positions.at(pieces[faces[i][0]]);
        const auto b=saber.positions.at(pieces[faces[i][1]]);
        const auto c=saber.positions.at(pieces[faces[i][2]]);
        const Vec3 u{b.x-a.x,b.y-a.y,b.z-a.z},v{c.x-b.x,c.y-b.y,c.z-b.z};
        Vec3 n{u.y*v.z-u.z*v.y,u.z*v.x-u.x*v.z,u.x*v.y-u.y*v.x};
        // ProcessVerts (K2 0xb6ca2) preserves zero crosses and normalizes
        // other sums with Vector::Normalize's float length and 1e-9 limit.
        const auto length=std::sqrt((n.x*n.x+n.y*n.y)+n.z*n.z);
        if(length!=0.0f) {
            if(static_cast<double>(length)<1e-9) n={1.0f,0.0f,0.0f};
            else {const float scale=1.0f/length;n={n.x*scale,n.y*scale,n.z*scale};}
        }
        normals[i]=n;
    }
    struct Source {
        std::size_t piece{},index{};
        Vec3 color{1.0f,1.0f,1.0f};
    };
    std::vector<Source> sources;
    std::array<std::size_t,pieces.size()> sourceForPiece{};
    const auto sameRecord=[&](std::size_t a,std::size_t b) {
        return std::memcmp(&saber.positions.at(a),&saber.positions.at(b),sizeof(Vec3))==0 &&
               std::memcmp(&saber.normals.at(a),&saber.normals.at(b),sizeof(Vec3))==0 &&
               std::memcmp(&saber.texcoords.at(a),&saber.texcoords.at(b),sizeof(Vec2))==0;
    };
    for(std::size_t i=0;i<pieces.size();++i) {
        const bool rear=i>=LightsaberNodeData::pieceVertices;
        auto found=std::find_if(sources.begin(),sources.end(),[&](const Source& source) {
            return (rear?source.color.z:source.color.x)==1.0f && sameRecord(source.piece,pieces[i]);
        });
        const auto index=static_cast<std::size_t>(found-sources.begin());
        if(found==sources.end()) {sources.push_back({pieces[i]});found=sources.end()-1;}
        const float selector=static_cast<float>(i%LightsaberNodeData::pieceVertices)/255.0f;
        (rear?found->color.z:found->color.x)=selector;
        sourceForPiece[i]=index;
    }
    // With smoothing zero each face appends three normal rows. Saber then
    // reads that pool by selector SOURCE index (K2 0xb8f90), not face corner.
    // Reorder source rows and faces together to retain the closest available
    // normal for each selected piece; no additional geometry is introduced.
    std::array<std::size_t,faces.size()> used{},faceIndex{};
    std::vector<std::size_t> faceOrder;
    for(auto& source:sources) {
        std::size_t selected=faces.size();
        double best=std::numeric_limits<double>::infinity();
        const auto desired=saber.normals.at(source.piece);
        for(std::size_t i=0;i<faces.size();++i) {
            if(used[i]==3u) continue;
            const double x=double(normals[i].x)-desired.x;
            const double y=double(normals[i].y)-desired.y;
            const double z=double(normals[i].z)-desired.z;
            const double error=x*x+y*y+z*z;
            if(selected==faces.size() || error<best) {selected=i;best=error;}
        }
        if(used[selected]==0u) {faceIndex[selected]=faceOrder.size();faceOrder.push_back(selected);}
        source.index=faceIndex[selected]*3u+used[selected]++;
    }
    for(std::size_t i=0;i<faces.size();++i)
        if(used[i]==0u) faceOrder.push_back(i);
    std::size_t count{};
    for(const auto& source:sources) count=std::max(count,source.index+1u);
    std::vector<std::size_t> vertices(count);
    std::vector<Vec3> colors(count,{1.0f,1.0f,1.0f});
    for(std::size_t i=0;i<count;++i) vertices[i]=pieces[faces[faceOrder[i/3u]][i%3u]];
    for(const auto& source:sources) {vertices[source.index]=source.piece;colors[source.index]=source.color;}
    writer.line("verts "+std::to_string(count));
    for(const auto index:vertices) writer.line(writer.vector(saber.positions.at(index)));
    if(explicitNormals) {
        writer.explicitNormalNote();
        writer.line("normals "+std::to_string(count));
        for(const auto index:vertices) writer.line(writer.vector(saber.normals.at(index)));
    }
    writer.line("tverts "+std::to_string(count));
    for(const auto index:vertices) {
        const auto uv=saber.texcoords.at(index);
        writer.line(writer.scalar(uv.x)+" "+writer.scalar(uv.y)+" 0");
    }
    writer.line("colors "+std::to_string(count));
    for(const auto color:colors) writer.line(writer.vector(color));
    writer.line("faces "+std::to_string(faces.size()));
    for(const auto index:faceOrder) {
        const auto& face=faces[index];
        const auto a=std::to_string(sources[sourceForPiece[face[0]]].index);
        const auto b=std::to_string(sources[sourceForPiece[face[1]]].index);
        const auto c=std::to_string(sources[sourceForPiece[face[2]]].index);
        // The blade's fixed strips do not consume source face materials.
        writer.line(a+" "+b+" "+c+" 0 "+a+" "+b+" "+c+" 0");
    }
    writer.warning("Lightsaber "+node.name+
        ": source faces and selector colors are reconstructed from the blade pieces; ASCII load regenerates "+
        (explicitNormals?std::string("the mesh sphere, which may differ from its stored value."):
            std::string("normals and the mesh sphere, which may differ from their stored values.")));
}

